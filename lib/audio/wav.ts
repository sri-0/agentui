/** The sample rate transcription models take. */
const RATE = 16_000;

/**
 * A recording as 16 kHz mono 16-bit WAV, the format every transcription route
 * accepts (browsers record WebM or MP4, which Voxtral refuses).
 */
export async function toWav(recording: Blob): Promise<Blob> {
  // Decoding in an offline context resamples to RATE; rendering into one
  // channel mixes down.
  const decoded = await new OfflineAudioContext(1, 1, RATE).decodeAudioData(await recording.arrayBuffer());
  const offline = new OfflineAudioContext(1, decoded.length, RATE);
  const source = offline.createBufferSource();
  source.buffer = decoded;
  source.connect(offline.destination);
  source.start();
  const samples = (await offline.startRendering()).getChannelData(0);

  const view = new DataView(new ArrayBuffer(44 + samples.length * 2));
  const ascii = (at: number, s: string) => [...s].forEach((c, i) => view.setUint8(at + i, c.charCodeAt(0)));
  ascii(0, "RIFF");
  view.setUint32(4, 36 + samples.length * 2, true);
  ascii(8, "WAVE");
  ascii(12, "fmt ");
  view.setUint32(16, 16, true); // fmt chunk size
  view.setUint16(20, 1, true); // PCM
  view.setUint16(22, 1, true); // mono
  view.setUint32(24, RATE, true);
  view.setUint32(28, RATE * 2, true); // bytes per second
  view.setUint16(32, 2, true); // bytes per sample
  view.setUint16(34, 16, true); // bits per sample
  ascii(36, "data");
  view.setUint32(40, samples.length * 2, true);
  samples.forEach((s, i) => view.setInt16(44 + i * 2, Math.max(-1, Math.min(1, s)) * 0x7fff, true));
  return new Blob([view], { type: "audio/wav" });
}
